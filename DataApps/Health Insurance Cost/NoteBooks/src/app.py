from pathlib import Path

import joblib
import pandas as pd
import streamlit as st


st.set_page_config(
    page_title="Health Insurance Cost Predictor",
    page_icon="🏥",
    layout="centered",
)

APP_DIR = Path(__file__).resolve().parent


@st.cache_resource
def load_artifacts():
    files = {
        "scaler": "scaler.pkl",
        "gender_encoder": "label_encoder_gender.pkl",
        "diabetic_encoder": "label_encoder_diabetic.pkl",
        "smoker_encoder": "label_encoder_smoker.pkl",
        "model": "best_model.pkl",
    }

    missing = [filename for filename in files.values()
               if not (APP_DIR / filename).is_file()]
    if missing:
        raise FileNotFoundError(
            f"Missing model file(s) in {APP_DIR}: {', '.join(missing)}"
        )

    return {
        key: joblib.load(APP_DIR / filename)
        for key, filename in files.items()
    }


